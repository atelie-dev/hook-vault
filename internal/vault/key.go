// Package vault implements hook-vault's cryptographic contract.
//
// Payloads are sealed with an anonymous sealed box (X25519 +
// XSalsa20-Poly1305), byte-compatible with libsodium's crypto_box_seal. The
// server holds only the recipient's public key, so it can store a payload but
// never read it.
//
// The read API token is derived from the same secret key with HKDF under a
// distinct info string. That is deliberate: a bearer token travels on every
// request and ends up in proxy logs, so it must never be the key that opens the
// archive. Leaking the token reveals neither the secret key nor any other
// material derived from it.
package vault

import (
	"crypto/ecdh"
	"crypto/hkdf"
	"crypto/rand"
	"crypto/sha256"
	"crypto/subtle"
	"encoding/base32"
	"encoding/base64"
	"errors"
	"fmt"
	"strings"

	"golang.org/x/crypto/nacl/box"
)

const (
	// SecretKeySize is the size of an X25519 secret key.
	SecretKeySize = 32
	// PublicKeySize is the size of an X25519 public key.
	PublicKeySize = 32
	// AnonymousOverhead is the overhead a sealed box adds to a payload.
	AnonymousOverhead = box.AnonymousOverhead
	// TokenPrefix makes bearer tokens recognisable in logs and secret scanners.
	TokenPrefix = "hv1_"

	// tokenInfo is the HKDF domain separation string for the API token.
	tokenInfo = "hook-vault.auth.v1"
)

// ErrKeySize is returned when a key is not 32 bytes long.
var ErrKeySize = errors.New("vault: key must be 32 bytes")

// ErrOpen is returned when a ciphertext cannot be opened with the given key.
var ErrOpen = errors.New("vault: ciphertext cannot be opened with this key")

// kIDEncoding is a lowercase base32 alphabet, so key ids survive being pasted
// into URLs, logs and clipboard-hostile chat clients.
var kIDEncoding = base32.NewEncoding("abcdefghijklmnopqrstuvwxyz234567").WithPadding(base32.NoPadding)

// Key is a complete credential set derived from one 32-byte secret.
type Key struct {
	Secret [32]byte
	Public [32]byte
	KID    string
	Token  string
}

// Generate creates a fresh key from crypto/rand.
func Generate() (*Key, error) {
	var secret [32]byte
	if _, err := rand.Read(secret[:]); err != nil {
		return nil, fmt.Errorf("vault: read random: %w", err)
	}
	return FromSecret(secret[:])
}

// FromSecret derives the public key, key id and API token from a secret key.
//
// The input is exactly what libsodium calls the secret key: 32 raw bytes, as
// produced by crypto_box_keypair. Clamping happens at use time on both sides,
// so keys generated by either implementation are interchangeable.
func FromSecret(secret []byte) (*Key, error) {
	if len(secret) != SecretKeySize {
		return nil, ErrKeySize
	}

	var k Key
	copy(k.Secret[:], secret)

	priv, err := ecdh.X25519().NewPrivateKey(k.Secret[:])
	if err != nil {
		return nil, fmt.Errorf("vault: derive public key: %w", err)
	}
	copy(k.Public[:], priv.PublicKey().Bytes())

	token, err := TokenFor(secret)
	if err != nil {
		return nil, err
	}
	k.Token = token
	k.KID = KIDFor(k.Public[:])

	return &k, nil
}

// TokenFor derives the bearer token for a secret key.
//
// Deterministic by design: the same secret always yields the same token, so a
// consumer can recover it after a restore instead of storing it next to the key.
func TokenFor(secret []byte) (string, error) {
	if len(secret) != SecretKeySize {
		return "", ErrKeySize
	}
	raw, err := hkdf.Key(sha256.New, secret, nil, tokenInfo, 32)
	if err != nil {
		return "", fmt.Errorf("vault: derive token: %w", err)
	}
	return TokenPrefix + base64.RawURLEncoding.EncodeToString(raw), nil
}

// KIDFor returns the stable key id for a public key.
func KIDFor(public []byte) string {
	sum := sha256.Sum256(public)
	return "k" + kIDEncoding.EncodeToString(sum[:])[:10]
}

// SealTo encrypts plaintext for the holder of the key pair that owns public.
func SealTo(plaintext []byte, public *[32]byte) ([]byte, error) {
	sealed, err := box.SealAnonymous(nil, plaintext, public, rand.Reader)
	if err != nil {
		return nil, fmt.Errorf("vault: seal: %w", err)
	}
	return sealed, nil
}

// Open decrypts a sealed box. Both halves of the recipient key pair are needed:
// the public key participates in the nonce derivation.
func Open(ciphertext []byte, public, secret *[32]byte) ([]byte, error) {
	if len(ciphertext) < AnonymousOverhead {
		return nil, ErrOpen
	}
	plaintext, ok := box.OpenAnonymous(nil, ciphertext, public, secret)
	if !ok {
		return nil, ErrOpen
	}
	return plaintext, nil
}

// HashToken returns the value stored server-side to authenticate a token.
func HashToken(token string) []byte {
	sum := sha256.Sum256([]byte(token))
	return sum[:]
}

// TokensEqual compares two tokens without leaking their content through timing.
func TokensEqual(a, b string) bool {
	return subtle.ConstantTimeCompare([]byte(a), []byte(b)) == 1
}

// HashEqual compares two digests without leaking their content through timing.
func HashEqual(a, b []byte) bool {
	return subtle.ConstantTimeCompare(a, b) == 1
}

// EncodeSecret renders the secret key for humans and config files.
func EncodeSecret(secret []byte) string { return base64.RawURLEncoding.EncodeToString(secret) }

// EncodePublic renders the public key for humans and config files.
func EncodePublic(public []byte) string { return base64.RawURLEncoding.EncodeToString(public) }

// ParsePublicKey accepts a base64-encoded 32-byte X25519 public key, with or
// without padding, URL or standard alphabet.
func ParsePublicKey(s string) (*[32]byte, error) {
	s = strings.TrimSpace(s)
	for _, enc := range []*base64.Encoding{
		base64.RawURLEncoding,
		base64.URLEncoding,
		base64.RawStdEncoding,
		base64.StdEncoding,
	} {
		if raw, err := enc.DecodeString(s); err == nil && len(raw) == PublicKeySize {
			var public [32]byte
			copy(public[:], raw)
			return &public, nil
		}
	}
	return nil, fmt.Errorf("vault: public key must be 32 bytes encoded as base64, got %d characters", len(s))
}
